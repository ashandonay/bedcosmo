"""bedcosmo.response_surface: polynomial fits of EIG over a design pool, and effect paths."""
import numpy as np
import pytest

from bedcosmo.response_surface import ResponseSurface, is_mixture


def _simplex(step=0.1, q=3):
    if q == 3:
        return np.array([(a, b, round(1 - a - b, 10)) for a in np.arange(0, 1 + 1e-9, step)
                         for b in np.arange(0, 1 - a + 1e-9, step)])
    raise NotImplementedError


def test_is_mixture():
    assert is_mixture(_simplex())
    assert is_mixture(2 * _simplex())          # any constant total
    assert not is_mixture(np.random.default_rng(0).uniform(size=(10, 3)))


@pytest.mark.parametrize("order", ["linear", "quadratic", "cubic"])
def test_mixture_fit_is_exact_for_its_own_order(order):
    """Values generated by a surface of the same order are fit exactly."""
    X = _simplex()
    template = ResponseSurface(X, X[:, 0], order=order)
    coef = np.random.default_rng(1).normal(size=template.n_params)
    fit = ResponseSurface(X, template.predict(X, coef), order=order)
    assert fit.mixture and fit.r2 == pytest.approx(1.0) and fit.loo_rmse < 1e-8
    assert fit.coef == pytest.approx(coef)
    assert fit.n_params == {"linear": 3, "quadratic": 6, "cubic": 10}[order]


def test_mixture_fit_uses_proportions():
    """Scaling every design by the same total does not change the fit."""
    X = _simplex()
    y = X[:, 0] * X[:, 1] + X[:, 2]
    a, b = ResponseSurface(X, y), ResponseSurface(3 * X, y)
    assert a.coef == pytest.approx(b.coef)
    assert a.predict(X) == pytest.approx(b.predict(3 * X))


def test_cox_path_keeps_the_other_proportions():
    X = _simplex()
    surf = ResponseSurface(X, X[:, 0])
    t, path = surf.trace(0, [0.2, 0.2, 0.6], n=11)
    assert t[0] == pytest.approx(0.0) and t[-1] == pytest.approx(1.0)
    assert path.sum(axis=1) == pytest.approx(np.ones(11))
    ok = path[:, 2] > 0
    assert path[ok, 1] / path[ok, 2] == pytest.approx(np.full(ok.sum(), 1 / 3))


def test_ordinary_path_holds_the_others():
    X = np.random.default_rng(2).uniform(size=(40, 3))
    surf = ResponseSurface(X, X @ [1.0, 2.0, 3.0])
    assert not surf.mixture and surf.coef[0] == pytest.approx(
        np.mean(X @ [1.0, 2.0, 3.0]), abs=1e-6)  # intercept in standardized coordinates
    t, path = surf.trace(1, [0.5, 0.5, 0.5], n=5)
    assert path[:, [0, 2]] == pytest.approx(np.full((5, 2), 0.5))
    assert t == pytest.approx(np.linspace(X[:, 1].min(), X[:, 1].max(), 5))


def test_too_few_designs_for_the_order():
    X = _simplex(step=0.5)                      # 6 designs; a 3-component cubic needs 10
    with pytest.raises(ValueError, match="lower order"):
        ResponseSurface(X, X[:, 0], order="cubic")
    with pytest.raises(ValueError, match="order must be"):
        ResponseSurface(X, X[:, 0], order="quartic")


def test_confidence_band_matches_simple_regression():
    """One input, linear fit: the textbook band t * s * sqrt(1/n + (x - xbar)^2 / Sxx)."""
    from scipy.stats import t as student_t

    rng = np.random.default_rng(3)
    x = rng.uniform(0, 1, 30)
    y = 1.0 + 2.0 * x + 0.1 * rng.normal(size=30)
    surf = ResponseSurface(x[:, None], y, order="linear")
    xs = np.linspace(0, 1, 5)
    fit, half = surf.confidence_band(xs[:, None], level=95)
    b1, b0 = np.polyfit(x, y, 1)
    s = np.sqrt(np.sum((y - b0 - b1 * x) ** 2) / 28)
    expect = student_t.ppf(0.975, 28) * s * np.sqrt(1 / 30 + (xs - x.mean()) ** 2
                                                    / np.sum((x - x.mean()) ** 2))
    assert fit == pytest.approx(b0 + b1 * xs) and half == pytest.approx(expect)
    assert surf.dof == 28


def test_band_relative_to_a_reference_vanishes_there():
    X = _simplex()
    y = X[:, 0] * X[:, 1] + 0.05 * np.random.default_rng(4).normal(size=len(X))
    surf = ResponseSurface(X, y)
    ref = np.array([0.2, 0.3, 0.5])
    fit, half = surf.confidence_band(np.vstack([ref, [0.6, 0.2, 0.2]]), reference=ref)
    assert fit[0] == pytest.approx(0.0, abs=1e-12) and half[0] == pytest.approx(0.0, abs=1e-9)
    assert half[1] > 0


def test_coefficient_draws_follow_the_covariance():
    X = _simplex()
    y = X[:, 0] + 0.1 * np.random.default_rng(5).normal(size=len(X))
    surf = ResponseSurface(X, y)
    draws = surf.sample_coefs(n=20000)
    assert draws.mean(axis=0) == pytest.approx(surf.coef, abs=0.02)
    assert np.cov(draws.T) == pytest.approx(surf.cov, abs=2e-3)
